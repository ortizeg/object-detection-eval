"""Render ``cost_per_frame.json`` to ``COST.md`` and ``cost_vs_accuracy.png``.

Both renderers read ONLY the :class:`CostReport` (the parsed JSON): no usage log, no
config file. The Markdown is a pure, deterministic function of the report, so
``scripts/cost_report.py --check`` can prove the committed file is exactly what the
committed JSON generates. ``matplotlib`` is imported inside the plotting function so
importing this module stays light.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from object_detection_eval.cost.schemas import CostReport, PipelineStats, PublishedEntry

GENERATED_HEADER = (
    "<!-- GENERATED by scripts/cost_report.py from "
    "benchmarks/basketball/results/cost/cost_per_frame.json. Do not edit by hand: "
    "edit the inputs and rerun the script. -->"
)
CURRENT = "current"
POST = "post_2026_12_01"


# ----------------------------------------------------------------------- formatting


def _usd(x: float | None, digits: int = 4) -> str:
    return "n/a (unpriced)" if x is None else f"${x:.{digits}f}"


def _usd_sd(mean: float | None, sd: float | None) -> str:
    if mean is None:
        return "n/a (unpriced)"
    return f"${mean:.4f} ± ${sd:.4f}" if sd is not None else f"${mean:.4f}"


def _per_1000(x: float | None) -> str:
    return "n/a" if x is None else f"${x:,.2f}"


def _secs(mean: float, sd: float | None) -> str:
    return f"{mean:.1f} ± {sd:.1f}" if sd is not None else f"{mean:.1f}"


def _acc(entry: PublishedEntry, field: str) -> str:
    cv = entry.test_map5095 if field == "map" else entry.recall_at_p95
    if cv.value is None:
        return f"n/a ({cv.reason})"
    return f"{cv.value:.3f}"


def _calls(stats: PipelineStats) -> str:
    suffix = "*" if stats.calls_aggregation == "sum_of_members" else ""
    return f"{stats.calls_per_frame_mean:.1f} ({stats.calls_per_frame_max}){suffix}"


def _sort_key(stats: PipelineStats) -> tuple[int, float, str]:
    usd = stats.usd[CURRENT]
    if usd.mean is not None:
        return (0, usd.mean, stats.id)
    return (1, usd.lower_bound_mean or 0.0, stats.id)


def _workers(stats: PipelineStats) -> str:
    return str(stats.workers) if stats.workers is not None else "n/a"


# ----------------------------------------------------------------------------- tables


def _headline_table(report: CostReport) -> list[str]:
    rows = [
        "| Pipeline | test mAP@50:95 | recall@95%P | calls/frame mean (max) "
        "| USD/frame now | USD per 1,000 frames now | USD/frame from 2026-12-01 "
        "| USD per 1,000 from 2026-12-01 | s/frame serial | s/frame at published workers (N) |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for stats in sorted(report.pipelines.values(), key=_sort_key):
        entry = report.accuracy.pipelines[stats.id]
        now, post = stats.usd[CURRENT], stats.usd[POST]
        now_cell = _usd_sd(now.mean, now.sd)
        if now.mean is None and now.lower_bound_mean is not None:
            now_cell += f" (lower bound ${now.lower_bound_mean:.4f})"
        conc = _secs(stats.concurrent_s_per_frame.mean, stats.concurrent_s_per_frame.sd)
        conc += "†" if stats.kind == "derived" else f" ({_workers(stats)})"
        rows.append(
            f"| {stats.label} | {_acc(entry, 'map')} | {_acc(entry, 'recall')} | {_calls(stats)} "
            f"| {now_cell} | {_per_1000(now.per_1000_frames)} "
            f"| {_usd_sd(post.mean, post.sd)} | {_per_1000(post.per_1000_frames)} "
            f"| {_secs(stats.serial_s_per_frame.mean, stats.serial_s_per_frame.sd)} | {conc} |"
        )
    return rows


def _detail_table(report: CostReport) -> list[str]:
    rows = [
        "| Pipeline | calls pass 1 | calls pass 2 | input tok/frame (text / image / cached) "
        "| billable output tok/frame | of which reasoning | retries | errors |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]

    def tok(x: float | None) -> str:
        return "n/a" if x is None else f"{x:,.0f}"

    for stats in sorted(report.pipelines.values(), key=_sort_key):
        t = stats.tokens_per_frame_mean
        rows.append(
            f"| {stats.label} | {stats.calls_by_pass_mean.get('1', 0.0):.1f} "
            f"| {stats.calls_by_pass_mean.get('2', 0.0):.1f} "
            f"| {tok(t['input'])} ({tok(t['input_text'])} / {tok(t['input_image'])} "
            f"/ {tok(t['cached_input'])}) "
            f"| {tok(t['billable_output'])} | {tok(t['reasoning'])} "
            f"| {stats.retries} | {stats.errors} |"
        )
    return rows


def _price_table(report: CostReport) -> list[str]:
    rows = ["| Model id | Provider | Period | Price | Source |", "| --- | --- | --- | --- | --- |"]
    for model_id in sorted(report.prices.models):
        model = report.prices.models[model_id]
        for p in model.periods:
            start = p.effective_from.isoformat() if p.effective_from else "..."
            end = p.effective_to.isoformat() if p.effective_to else "..."
            if model.unit == "per_call":
                price = (
                    f"${p.per_call_usd} per call"
                    if p.per_call_usd is not None
                    else "per-call price not yet supplied"
                )
            else:
                price = f"${p.input_per_1m:g} in / ${p.output_per_1m:g} out per 1M tokens"
            rows.append(
                f"| {model_id} | {model.provider} | {start} to {end} | {price} | {p.source_url} |"
            )
    return rows


def _accuracy_table(report: CostReport) -> list[str]:
    rows = ["| Pipeline | Metric | Value | Source |", "| --- | --- | --- | --- |"]
    for pid, entry in report.accuracy.pipelines.items():
        for name, cv in (
            ("test mAP@50:95", entry.test_map5095),
            ("recall@95%P", entry.recall_at_p95),
        ):
            value = f"{cv.value:.3f}" if cv.value is not None else f"n/a ({cv.reason})"
            src = cv.source
            where = (
                f"`{src.file}` ({src.section or src.json_path})" if src.file else (src.note or "")
            )
            rows.append(f"| {pid} | {name} | {value} | {where} |")
    for ref in report.accuracy.reference_lines:
        cv = ref.test_map5095
        src = cv.source
        rows.append(
            f"| {ref.label} | test mAP@50:95 | {cv.value:.3f} | `{src.file}` ({src.section}) |"
        )
    return rows


def _runs_table(report: CostReport) -> list[str]:
    rows = [
        "| Pipeline | Run | Frames | Workers | Run wall (s) | Status | git | Env |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for m in report.manifests:
        rows.append(
            f"| {m.pipeline} | {m.run} | {m.n_frames} | {m.workers} | {m.wall_s:.1f} "
            f"| {m.status} | {(m.git_sha or 'n/a')[:10]} | {m.pixi_env or 'n/a'} |"
        )
    return rows


def _workers_table(report: CostReport) -> list[str]:
    rows = ["| Pipeline | Published --workers | Evidence |", "| --- | --- | --- |"]
    for stats in report.pipelines.values():
        if stats.kind == "pipeline":
            rows.append(f"| {stats.id} | {_workers(stats)} | {stats.workers_citation} |")
    return rows


# ---------------------------------------------------------------------------- markdown


def render_markdown(report: CostReport, figure_href: str = "cost_vs_accuracy.png") -> str:
    """The COST.md text. Deterministic: the same report always yields the same bytes.

    ``figure_href`` is the PNG's path relative to COST.md.
    """
    n_frames = sorted({n for s in report.pipelines.values() for n in s.n_frames_per_run})
    frames_txt = "/".join(str(n) for n in n_frames)
    n_runs = max(len(s.runs) for s in report.pipelines.values())
    lines: list[str] = [
        GENERATED_HEADER,
        "",
        "# What each zero-shot pipeline costs per frame",
        "",
        f"Each pipeline was rerun on {frames_txt} validation frames, {n_runs} times, with every "
        "response cache and checkpoint bypassed and at the `--workers` it was published "
        "with. The test split was not touched: USD and seconds are measured on validation "
        "frames (1920x1080 on every split, so image-token counts transfer), and the accuracy "
        "columns are copied from the committed reports, not recomputed. Cost comes from "
        "per-call usage logs (`benchmarks/basketball/results/cost/usage/`) priced with a "
        "committed table (`conf/cost_prices.yaml`); nothing is hand arithmetic.",
        "",
        "Read the numbers with these limits in mind:",
        "",
        f"- With {n_runs} runs the run-to-run SD is a rough indication, not a confidence interval.",
        "- Latency depends on provider load and the time of day; it is one afternoon's "
        "measurement, not a service-level figure.",
        "- The Gemini 4 Argon price doubles on 2026-12-01 (input $2 to $4, output $10 to $20 "
        "per 1M tokens). Both prices are shown.",
        "- DINO-X is billed per call, in CNY, from a console balance. Its price is an "
        "approximate per-call figure converted to USD at a dated exchange rate (see the note "
        "in `conf/cost_prices.yaml`). A model with no price is shown unpriced, and any fused "
        "line containing it carries a lower bound that leaves it out.",
        "- Single-run accuracy gaps of about 2 points between the API rows are within the "
        'published run-to-run noise (VLM_VS_FINETUNED.md, "Parity with the Ultralytics Platform '
        'benchmark"). Do not read a ranking into small differences in the accuracy columns.',
        "",
        "## Headline",
        "",
        *_headline_table(report),
        "",
        "`calls/frame` counts every billed request for a frame, including second-pass crop "
        "calls and tile calls; the figure in brackets is the largest count for any single frame. "
        "USD is mean ± SD over the runs. `s/frame serial` is the mean of each frame's own wall "
        "time; `s/frame at published workers` is run wall time divided by frames, which is what "
        "the published concurrency delivers.",
        "",
        "\\* A fused line has no calls of its own: it is the sum of its members' calls "
        "(WBF itself is free). Its call mean is the sum of the members' means; its call max "
        "is the sum of the members' maxima, an upper bound rather than a joint statistic.",
        "",
        "† A fused line's latency is the sum of its members' (they run one after another). "
        "The slowest member alone is the lower bound if they ran in parallel:",
        "",
    ]
    for stats in sorted(report.pipelines.values(), key=_sort_key):
        if stats.kind == "derived" and stats.parallel_lower_bound_s_per_frame is not None:
            lines.append(
                f"- {stats.label}: serial sum {stats.serial_s_per_frame.mean:.1f} s/frame, "
                f"parallel lower bound {stats.parallel_lower_bound_s_per_frame:.1f} s/frame "
                f"(members: {', '.join(stats.members)})."
            )
    lines += ["", "## Calls and tokens", "", *_detail_table(report), ""]
    if any(s.cached_input_note for s in report.pipelines.values()):
        lines += [
            "Cached input tokens were reported for at least one pipeline and are billed at the "
            "full input rate here; the cost model has no cache discount.",
            "",
        ]
    lines += [
        "## Spend",
        "",
        f"The whole study cost **${report.study_spend_usd:.2f}** at the prices in force on each "
        "call's date, counting projection runs and any aborted run.",
    ]
    if report.study_unpriced_calls:
        parts = ", ".join(f"{m}: {n}" for m, n in report.study_unpriced_calls.items())
        lines += ["", f"Calls with no price yet (not in that total): {parts}."]
    lines += [
        "",
        f"![USD per frame against published accuracy]({figure_href})",
        "",
        "## Prices",
        "",
        *_price_table(report),
        "",
        "Reasoning and thinking tokens are billed at the output rate by all three token-priced "
        "providers; whether a response's `output_tokens` already includes them is recorded per "
        "call, so reasoning is neither double-counted nor missed.",
        "",
        "## Where each accuracy number comes from",
        "",
        *_accuracy_table(report),
        "",
        "## Runs",
        "",
        *_runs_table(report),
        "",
        *_workers_table(report),
        "",
        "## Billing cross-check",
        "",
        "The OpenAI and Anthropic admin billing checks were skipped by user decision on "
        "2026-10-27, so this report has no billing-comparison column. The Google Cloud export "
        "and the DeepDataSpace console steps are written up for the user to perform: "
        "[Google Cloud Billing export](../../../docs/cost/gcp-billing-export.md) and "
        "[DINO-X console checklist](../../../docs/cost/dinox-console-checklist.md).",
    ]
    if report.notes:
        lines += ["", "## Notes", ""] + [f"- {n}" for n in report.notes]
    lines += [
        "",
        "## Reproducing this page",
        "",
        "```",
        "pixi run python scripts/cost_report.py",
        "pixi run python scripts/cost_report.py --check",
        "```",
        "",
    ]
    return "\n".join(lines)


# ------------------------------------------------------------------------------- plot


@dataclass(frozen=True)
class PlotPoint:
    id: str
    label: str
    x: float
    x_sd: float | None
    map_y: float | None
    recall_y: float | None


def plot_points(report: CostReport) -> tuple[list[PlotPoint], list[str]]:
    """The points the PNG draws, and a footnote line for each point left out and why."""
    points: list[PlotPoint] = []
    skipped: list[str] = []
    for stats in sorted(report.pipelines.values(), key=_sort_key):
        entry = report.accuracy.pipelines[stats.id]
        usd = stats.usd[CURRENT]
        if usd.mean is None:
            skipped.append(f"{stats.label}: not plotted, unpriced (no per-call price yet)")
            continue
        map_y = entry.test_map5095.value
        recall_y = entry.recall_at_p95.value
        if recall_y is None:
            skipped.append(
                f"{stats.label}: not on the recall panel, recall@95%P {entry.recall_at_p95.reason}"
            )
        if map_y is None:  # pragma: no cover - every published row has an mAP
            skipped.append(f"{stats.label}: not on the mAP panel, mAP {entry.test_map5095.reason}")
        points.append(PlotPoint(stats.id, stats.label, usd.mean, usd.sd, map_y, recall_y))
    return points, skipped


#: Point labels for the figure; the full labels are too long to sit next to a marker.
_SHORT_LABELS: dict[str, str] = {
    "astra": "Astra",
    "astra_crop_refine": "Astra crop-refine",
    "sol": "Sol",
    "claude_opus": "Opus 5.5",
    "gemini_argon_single": "Argon single pass",
    "gemini_argon_two_pass": "Argon two-pass",
    "dinox_pro_rimtrim": "DINO-X Pro",
    "dinox_preview_rimtrim": "DINO-X preview",
    "api_fusion4": "API-rows fusion",
    "fusion4": "Best zero-shot fusion",
}

#: Per-panel label offsets (points) and alignment where the default would collide or
#: clip: DINO-X Pro and preview share a cost and swap order between the panels; the
#: dearest point sits on the right edge.
_LABEL_PLACEMENT: dict[tuple[str, str], tuple[float, float, str]] = {
    ("map_y", "dinox_preview_rimtrim"): (5, -11, "left"),
    ("recall_y", "dinox_pro_rimtrim"): (5, -11, "left"),
    ("map_y", "fusion4"): (-5, 4, "right"),
    ("recall_y", "fusion4"): (-5, 4, "right"),
}


def render_png(report: CostReport, path: Path) -> list[str]:
    """Write the two-panel figure; return the footnote lines (points left out and why)."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    points, skipped = plot_points(report)
    fig, (ax_map, ax_rec) = plt.subplots(1, 2, figsize=(14, 6.5), sharex=True)
    # One colour per pipeline, the same in both panels.
    colors = {p.id: plt.get_cmap("tab10")(i % 10) for i, p in enumerate(points)}
    for ax, field, title in (
        (ax_map, "map_y", "Test mAP@50:95"),
        (ax_rec, "recall_y", "Test recall at 95% precision"),
    ):
        ax.set_xscale("log")
        ax.set_title(title)
        ax.set_xlabel("USD per frame (log scale), validation-frame measurement")
        ax.set_ylabel(title)
        ax.grid(True, alpha=0.3)
        for p in points:
            y = getattr(p, field)
            if y is None:
                continue
            xerr = None
            if p.x_sd is not None:
                lower = min(p.x_sd, p.x * 0.95)  # keep the lower bar positive on a log axis
                xerr = [[lower], [p.x_sd]]
            ax.errorbar(p.x, y, xerr=xerr, fmt="o", capsize=3, markersize=6, color=colors[p.id])
            label = _SHORT_LABELS.get(p.id, p.id)
            dx, dy, ha = _LABEL_PLACEMENT.get((field, p.id), (5, 4, "left"))
            ax.annotate(
                label,
                (p.x, y),
                textcoords="offset points",
                xytext=(dx, dy),
                ha=ha,
                fontsize=8,
            )
    for ref in report.accuracy.reference_lines:
        if ref.test_map5095.value is not None:
            ax_map.axhline(ref.test_map5095.value, linestyle="--", color="gray", linewidth=1)
            ax_map.annotate(
                f"{ref.label} {ref.test_map5095.value:.3f}",
                xy=(0.01, ref.test_map5095.value),
                xycoords=("axes fraction", "data"),
                xytext=(0, 3),
                textcoords="offset points",
                fontsize=8,
                color="gray",
            )
    if not points:
        ax_map.set_xlim(1e-3, 1.0)
    if skipped:
        fig.text(0.01, 0.01, "Not plotted: " + "; ".join(skipped), fontsize=7, wrap=True)
    fig.tight_layout(rect=(0, 0.06 if skipped else 0, 1, 1))
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=130)
    plt.close(fig)
    return skipped
