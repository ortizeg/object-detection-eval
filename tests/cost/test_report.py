def _load_script() -> ModuleType:
    path = REPO / "scripts" / "cost_report.py"
    spec = importlib.util.spec_from_file_location("cost_report_script", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["cost_report_script"] = module
    spec.loader.exec_module(module)
    return module


@pytest.fixture()
def script() -> ModuleType:
    return _load_script()


def _study_with_real_ids(results: Path) -> None:
    """Runs for four real pipeline ids, so the real accuracy config (with its citations) applies."""
    frames = ["a.jpg", "b.jpg"]
    for run in ("1", "2"):
        write_run(results, "astra", run, {f: [astra_call()] for f in frames})
        write_run(results, "sol", run, {f: [astra_call()] for f in frames})
        write_run(results, "claude_opus", run, {f: [astra_call()] for f in frames})
        write_run(results, "gemini_argon_two_pass", run, {f: [gemini_call()] for f in frames})


def _args(tmp_path: Path, *extra: str) -> list[str]:
    return [
        "--results-dir",
        str(tmp_path / "results"),
        "--report",
        str(tmp_path / "reports" / "COST.md"),
        "--prices",
        str(CONF / "cost_prices.yaml"),
        "--accuracy",
        str(CONF / "cost_published_accuracy.yaml"),
        *extra,
    ]


def test_script_exits_2_without_usage_logs(script: ModuleType, tmp_path: Path) -> None:
    assert script.main(_args(tmp_path)) == 2


def test_script_writes_json_md_png_and_check_gates_drift(
    script: ModuleType, tmp_path: Path
) -> None:
    _study_with_real_ids(tmp_path / "results")
    assert script.main(_args(tmp_path)) == 0

    out_json = tmp_path / "results" / "cost_per_frame.json"
    md = tmp_path / "reports" / "COST.md"
    png = tmp_path / "results" / "cost_vs_accuracy.png"
    assert out_json.is_file() and md.is_file() and png.stat().st_size > 0
    assert "(../results/cost_vs_accuracy.png)" in md.read_text()
    data = json.loads(out_json.read_text())
    assert "generated" not in json.dumps(data).lower()  # no wall-clock field: reproducible
    assert set(data["pipelines"]) == {
        "astra",
        "sol",
        "claude_opus",
        "gemini_argon_two_pass",
        "api_fusion4",
    }
    assert any(n.startswith("fusion4 not computed") for n in data["notes"])
    assert {i["path"] for i in data["inputs"]} >= {
        "usage/astra__1.jsonl",
        "benchmarks/basketball/conf/cost_prices.yaml",
    }
    assert all(len(i["sha256"]) == 64 for i in data["inputs"])
    # Markdown comes from the JSON alone
    assert md.read_text() == render_markdown(
        CostReport.model_validate_json(out_json.read_text()), "../results/cost_vs_accuracy.png"
    )

    assert script.main(_args(tmp_path, "--check")) == 0
    md.write_text(md.read_text() + "\nhand edit\n")
    assert script.main(_args(tmp_path, "--check")) == 1
    assert script.main(_args(tmp_path)) == 0  # regenerate
    out_json.write_text(out_json.read_text().replace('"study_spend_usd"', '"study_spend_usd_x"'))
    assert script.main(_args(tmp_path, "--check")) == 1


def test_script_check_fails_when_a_usage_log_changes(script: ModuleType, tmp_path: Path) -> None:
    _study_with_real_ids(tmp_path / "results")
    assert script.main(_args(tmp_path)) == 0
    write_run(
        tmp_path / "results",
        "astra",
        "2",
        {"a.jpg": [astra_call(), astra_call()], "b.jpg": [astra_call()]},
    )
    assert script.main(_args(tmp_path, "--check")) == 1


def test_script_refuses_an_aborted_run(script: ModuleType, tmp_path: Path) -> None:
    _study_with_real_ids(tmp_path / "results")
    write_run(tmp_path / "results", "astra", "2", {"a.jpg": [astra_call()]}, status="aborted")
    assert script.main(_args(tmp_path)) == 1


