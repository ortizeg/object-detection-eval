def test_markdown_is_a_pure_function_of_the_json(report: CostReport) -> None:
    text = render_markdown(report)
    again = render_markdown(CostReport.model_validate_json(report.model_dump_json()))
    assert text == again


def test_markdown_content(report: CostReport) -> None:
    md = render_markdown(report)
    assert md.startswith("<!-- GENERATED by scripts/cost_report.py")
    # sorted by current USD/frame: priced ascending (gemini 0.009 < astra 0.025 < fuse_ag),
    # then the unpriced ones
    order = [md.index(label) for label in ("Gemini two-pass |", "| Astra |", "| Astra + Gemini |")]
    assert order == sorted(order)
    assert md.index("| Astra + Gemini |") < md.index("| DINO-X Pro |")
    assert "$0.0250 ± $0.0071" in md  # mean ± SD (ddof=1)
    assert "$25.00" in md  # per 1,000 frames now
    assert "$0.0180" in md  # Gemini from 2026-12-01
    assert "n/a (unpriced)" in md  # DINO-X until the user supplies a price
    assert "lower bound $0.0250" in md  # fused line with an unpriced member
    assert "1.2 (2)" in md or "1.3 (2)" in md  # astra calls/frame mean (max)
    assert "n/a (not published)" in md  # recall without a published value
    assert "sum of its members' calls" in md
    assert "OpenAI and Anthropic admin billing checks were skipped by user decision" in md
    assert "gcp-billing-export.md" in md and "dinox-console-checklist.md" in md
    assert "within the published run-to-run noise" in md
    assert "![USD per frame against published accuracy](cost_vs_accuracy.png)" in md


def test_png_skips_unpriced_and_null_recall_and_says_why(
    report: CostReport, tmp_path: Path
) -> None:
    points, skipped = plot_points(report)
    assert {p.id for p in points} == {"astra", "gemini_argon_two_pass", "fuse_ag"}
    assert any("DINO-X Pro: not plotted, unpriced" in s for s in skipped)
    assert any("Astra: not on the recall panel" in s for s in skipped)
    out = tmp_path / "plot" / "cost_vs_accuracy.png"
    footnote = render_png(report, out)
    assert out.stat().st_size > 1000
    assert out.read_bytes()[:8] == b"\x89PNG\r\n\x1a\n"
    assert footnote == skipped


